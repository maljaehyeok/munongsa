const fs=require('fs'),vm=require('vm'),assert=require('assert');
global.document={addEventListener:()=>{},getElementById:()=>null};
for(const name of ['support-public','support-review','notice-review','personalization'])vm.runInThisContext(fs.readFileSync('assets/'+name+'.js','utf8'));
const P=MunongsaPersonalization;
const basic={title:'청년농업인 창업 지원',institution:'공식 기관',target:'unknown',support:'unknown'};
const related=P.discovery(basic,{farmingSituation:'preparing'},'김제에서 토마토 농사를 시작하려고 해');
assert(related.matches);assert(!related.eligibility_confirmed);
assert(!P.discovery(basic,{},'김제에서 토마토 재배하려고 해.').matches);
assert(P.discovery(basic,{farmingSituation:'preparing'},'김제에서 토마토 재배하려고 해.').broadened);
assert(!P.discovery({title:'농업인 건강검진',institution:'청년농업인 포털'}, {},'창업').matches,'portal audience is not business purpose');
assert(!P.discovery({title:'안전성 검사비 지원'}, {},'보험').matches,'inspection is not insurance');
assert(P.discovery({title:'온실 시설현대화'}, {},'시설 설치 관련 사업').matches);
const feed=JSON.parse(fs.readFileSync(process.argv[2]+'/feed.json','utf8'));
const profile={region:'제주',district:'제주시',residenceRegion:'제주',residenceDistrict:'제주시',applicant:'individual',farmRegistered:'no',farmingSituation:'preparing'};
const before=P.support(feed,profile),after=P.support(feed,{...profile,supportSearch:'시설'});
assert.deepEqual(Object.fromEntries(before.map(r=>[r.item.id,r.decision])),Object.fromEntries(after.map(r=>[r.item.id,r.decision])),'topic relevance cannot alter eligibility');
assert(after.some(r=>r.discovery.matches&&r.decision.region_state==='check'));
assert(after.every(r=>!r.decision.final_application_eligibility_confirmed));
assert(after.filter(r=>r.decision.excluded).every(r=>!r.recommendationAllowed));
assert(before.length===feed.notices.length);
console.log(JSON.stringify({related_without_eligibility:true,independent_decisions:before.length,unpublished_data_used:false}));
